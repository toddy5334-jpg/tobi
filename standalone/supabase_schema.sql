-- Esquema SQL para Supabase (PostgreSQL) — Proyecto: NutriMap AI
-- Ejecutar en Supabase -> SQL Editor -> New Query

CREATE TABLE IF NOT EXISTS establecimientos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  direccion VARCHAR(200) NOT NULL,
  contacto VARCHAR(100) NOT NULL,
  latitud DOUBLE PRECISION NOT NULL,
  longitud DOUBLE PRECISION NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  establecimiento_id BIGINT NOT NULL REFERENCES establecimientos(id) ON DELETE CASCADE,
  nombre VARCHAR(120) NOT NULL,
  categoria VARCHAR(80) NOT NULL,
  precio NUMERIC(12, 2) NOT NULL CHECK (precio >= 0),
  disponible BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_productos_establecimiento ON productos(establecimiento_id);
CREATE INDEX IF NOT EXISTS idx_productos_categoria ON productos(categoria);

-- Si usas la clave anon (publishable) en lugar de service_role, desactivamos RLS
-- y otorgamos permisos explícitos. Recomendado en producción: usar SUPABASE_KEY = service_role en el servidor.
ALTER TABLE establecimientos DISABLE ROW LEVEL SECURITY;
ALTER TABLE productos DISABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE establecimientos, productos TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

